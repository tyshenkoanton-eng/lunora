"""Рантайм-страж персональных данных (152-ФЗ) для пакета, уходящего в модель.

Защита в глубину. По контракту приватности в LLM уходят ТОЛЬКО градусы и текст —
без ФИО, даты и места рождения, пола, `user_id`, Telegram id, e-mail и телефона.
Регресс-тесты (`test_llm_privacy`, `test_llm_portrait_privacy`) фиксируют, что
СБОРКА пакета чиста. Этот модуль — активный предохранитель в РАНТАЙМЕ: единая
точка перед сетевым вызовом (`client._call_llm` на обоих путях — чат и портрет),
которая находит ПДн в служебной части пакета и, если находит, НЕ отправляет
(fail-closed).

Граница проверки — та же, что в регресс-тестах: вопрос пользователя и история
диалога — его собственные слова, по контракту границы продукта они не
фильтруются и в проверку не входят. Проверяется только служебная часть пакета:
системный промпт и данные карты.

Детектор обобщённый (по форме, без знания исходных значений): прежний закрытый
список дополнен e-mail и российским мобильным телефоном. Мобильный код РФ
начинается с 9 — это намеренно выводит из-под подозрения служебные номера вида
8-800-… (телефон доверия в аддендуме кризиса), которые не являются персональными.
"""

import re

CHART_MARKER = "## Данные натальной карты"
QUESTION_MARKER = "\n\n## Вопрос\n"

# Формы ПДн, узнаваемые без знания исходных значений.
_PATTERNS: dict[str, re.Pattern[str]] = {
    "e-mail": re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}"),
    # Российский мобильный: +7 или 8, затем код оператора 9XX и 7 цифр абонента.
    # Разделители (пробел, дефис, точка, скобки) допускаются. Код 9XX намеренно
    # исключает служебные 8-800-… — это не персональный номер.
    "телефон (РФ)": re.compile(r"(?:\+7|8)[\s\-.()]*9\d{2}(?:[\s\-.()]*\d){7}"),
    "дата (ISO)": re.compile(r"\b\d{4}-\d{2}-\d{2}\b"),
    "дата (ДД.ММ.ГГГГ)": re.compile(r"\b\d{1,2}\.\d{1,2}\.\d{4}\b"),
    "uuid": re.compile(
        r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b", re.IGNORECASE
    ),
    "telegram-подобный id": re.compile(r"\b\d{9,11}\b"),
}


def find_pii(text: str) -> list[str]:
    """Виды ПДн, найденные в тексте по форме. Пустой список — текст чист."""
    return sorted(kind for kind, pattern in _PATTERNS.items() if pattern.search(text))


def service_text(messages: list[dict]) -> str:
    """Служебная часть пакета: системный промпт + данные карты.

    Сообщение с картой (чат) — последнее пользовательское сообщение, начинающееся
    с маркера карты; из него берётся часть ДО маркера вопроса. Ищем с конца, чтобы
    враждебная реплика с маркером вопроса в истории не подменила карту и чтобы
    дозаписи ретрая не увели проверку от сообщения карты.

    Если сообщения карты нет (путь портрета — свободных слов пользователя в нём
    нет), служебными считаются все пользовательские сообщения пакета.
    """
    system = [m["content"] for m in messages if m["role"] == "system"]
    users = [m["content"] for m in messages if m["role"] == "user"]
    chart = next((u for u in reversed(users) if u.startswith(CHART_MARKER)), None)

    parts = list(system)
    if chart is not None:
        head, _sep, _tail = chart.partition(QUESTION_MARKER)
        parts.append(head)  # нет маркера вопроса → head == всё сообщение карты
    else:
        parts.extend(users)
    return "\n".join(parts)


class PiiInPackageError(RuntimeError):
    """Пакет для модели содержит ПДн в служебной части — отправка отменена.

    Несёт только ВИДЫ найденных ПДн (`kinds`), не значения: сообщение уходит в
    логи, и сами данные в нём появиться не должны.
    """

    def __init__(self, kinds: list[str]):
        self.kinds = list(kinds)
        super().__init__(
            "В служебной части пакета для модели обнаружены персональные данные: "
            + ", ".join(self.kinds)
            + ". Отправка отменена (fail-closed, 152-ФЗ)."
        )


def guard_package(messages: list[dict]) -> None:
    """Проверить служебную часть пакета; при ПДн — поднять `PiiInPackageError`.

    Единая точка контроля перед отправкой в модель. Fail-closed: при находке
    пакет в сеть не уходит.
    """
    kinds = find_pii(service_text(messages))
    if kinds:
        raise PiiInPackageError(kinds)
